    AUDIO, VIDEO;

    companion object {
        /** `movies` → VIDEO; `audio`, `etree` → AUDIO; anything else null (R07). */
        fun fromMediatype(mediatype: String?): MediaKind? = TODO()
    }
}

data class MediaFormat(val fileName: String, val format: String, val sizeBytes: Long?)

enum class SubtitleType { SRT, VTT }

data class SubtitleTrack(val fileName: String, val type: SubtitleType, val language: String?, val autoGenerated: Boolean)

/** One playable track/episode inside an item (R08, R10). [index] is the position after R11 ordering. */
data class Entry(
    val identifier: String,
    val index: Int,
    val title: String,
    val kind: MediaKind,
    val durationSeconds: Double?,
    val formats: List<MediaFormat>,
    val subtitles: List<SubtitleTrack>,
)

data class ArchiveItem(
    val identifier: String,
    val title: String,
    val creator: String?,
    val date: String?,
    val kind: MediaKind,
    val languages: Set<String>,
    val collections: List<String>,
    val subjects: List<String>,
    val description: String?,
    val artworkFile: String?,
    val entries: List<Entry>,
) {
    val isPlayable: Boolean get() = TODO()
    val archiveUrl: String get() = TODO()
}

data class SearchHit(
    val identifier: String,
    val title: String,
    val creator: String?,
    val kind: MediaKind?,
    val languages: Set<String>,
    val collections: List<String>,
    val subjects: List<String>,
    val downloads: Long,
    val date: String?,
)

data class SearchPage(val total: Int, val hits: List<SearchHit>)


package com.thomasnorlund.archiveplayer.core.catalog

import com.thomasnorlund.archiveplayer.core.support.Fixtures
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/** Contract tests against recorded archive.org metadata responses (fixtures recorded 7 Nov 2026). */
class MetadataParserTest {
    private fun item(name: String) = requireNotNull(MetadataParser.parse(Fixtures.archive(name))) { "parse returned null for $name" }

    @Test fun R08_R10_singleFilmIsOneVideoEntryWithAllFormats() {
        val film = item("AboutBan1935.metadata.json")
        assertEquals(MediaKind.VIDEO, film.kind)
        assertEquals("About Bananas", film.title)
        assertEquals(1, film.entries.size)
        val names = film.entries[0].formats.map { it.fileName }
        assertTrue(names.toString(), "AboutBan1935.mp4" in names)
        assertTrue(names.toString(), "AboutBan1935_512kb.mp4" in names)
        assertTrue(film.isPlayable)
    }

    @Test fun R10_nonMediaFilesAreNotEntriesButArtworkIsUsed() {
        val film = item("AboutBan1935.metadata.json")
        val all = film.entries.flatMap { e -> e.formats.map { it.fileName } }
        assertFalse(all.any { it.endsWith(".jpg") || it.endsWith(".png") || it.endsWith(".xml") || it.endsWith(".torrent") || it.endsWith(".gif") })
        assertEquals("__ia_thumb.jpg", film.artworkFile)
    }

    @Test fun R12_displayMetadata() {
        val film = item("AboutBan1935.metadata.json")
        assertEquals(listOf("prelinger"), film.collections)
        assertEquals(listOf("Agriculture: Bananas", "Central America"), film.subjects)
        assertEquals(emptySet<String>(), film.languages)
        assertEquals("https://archive.org/details/AboutBan1935", film.archiveUrl)
        assertEquals(664.03, film.entries[0].durationSeconds!!, 0.5)
    }

    @Test fun R07_R11_etreeConcertIsAudioAlbumInTrackOrder() {
        val show = item("jj2008-06-14.mk4.metadata.json")
        assertEquals(MediaKind.AUDIO, show.kind)
        assertEquals("Jack Johnson", show.creator)
        assertEquals(22, show.entries.size)
        assertEquals("Intro", show.entries[0].title)
        assertEquals("Go On", show.entries[10].title)
        assertEquals("If I Had Eyes", show.entries[21].title)
        assertEquals((0 until 22).toList(), show.entries.map { it.index })
        assertEquals(23.0, show.entries[0].durationSeconds!!, 0.5)
        assertTrue("JackJohnson" in show.collections)
    }

    @Test fun R10_originalAndDerivativesGroupedPerTrack() {
        val formats = item("jj2008-06-14.mk4.metadata.json").entries[0].formats.map { it.format }.toSet()
        assertTrue(formats.toString(), formats.containsAll(setOf("VBR MP3", "Ogg Vorbis", "Flac")))
    }

    @Test fun R11_A11_largeShowOrderedByTrackThenFilename() {
        val show = item("OTRR_Philip_Marlowe_Singles.metadata.json")
        assertEquals(105, show.entries.size)
        assertEquals("Who Shot Waldo", show.entries[0].title)
        assertEquals("The Red Wind", show.entries[1].title)
    }

    @Test fun R45_autogeneratedVttAttachesToItsEntry() {
        val show = item("OTRR_Philip_Marlowe_Singles.metadata.json")
        val subs = show.entries[0].subtitles
        assertEquals(1, subs.size)
        assertEquals(SubtitleType.VTT, subs[0].type)
        assertTrue(subs[0].autoGenerated)
        assertEquals("Philip_Marlowe_47-06-12_xxx_Who_Shot_Waldo.autogenerated.vtt", subs[0].fileName)
    }

    @Test fun A33_filmWithSrtOffersIt() {
        val film = item("his_girl_friday.metadata.json")
        assertEquals(MediaKind.VIDEO, film.kind)
        assertEquals("1940", film.date)
        val subs = film.entries.single().subtitles
        assertEquals(listOf("his_girl_friday.asr.srt"), subs.map { it.fileName })
        assertTrue(subs[0].autoGenerated)
    }

    @Test fun A40_humanAndMachineSubtitlesBothOfferedAndLabelled() {
        val json = """{"metadata":{"identifier":"film","mediatype":"movies","title":"Film"},"files":[
            {"name":"film.mpeg","source":"original","format":"MPEG2"},
            {"name":"film.mp4","source":"derivative","format":"h.264","original":"film.mpeg","length":"600"},
            {"name":"film.srt","source":"original","format":"SubRip"},
            {"name":"film.asr.srt","source":"original","format":"SubRip"}]}"""
        val subs = MetadataParser.parse(json)!!.entries.single().subtitles
        assertEquals(2, subs.size)
        assertEquals(setOf(false, true), subs.map { it.autoGenerated }.toSet())
    }

    @Test fun A12_itemWithOnlyImagesAndTextIsNotPlayable() {
        val json = """{"metadata":{"identifier":"x","mediatype":"movies","title":"X"},"files":[
            {"name":"x.jpg","source":"original","format":"JPEG"},{"name":"x.txt","source":"original","format":"Text"}]}"""
        val item = MetadataParser.parse(json)!!
        assertTrue(item.entries.isEmpty())
        assertFalse(item.isPlayable)
    }

    @Test fun R07_unsupportedMediaTypesExcluded() {
        assertNull(MetadataParser.parse("""{"metadata":{"identifier":"b","mediatype":"texts","title":"Book"},"files":[]}"""))
    }

    @Test fun R78_garbageNeverThrows() {
        listOf("", "{}", "not json", "[]", """{"metadata":null}""", """{"metadata":{"mediatype":"audio"}}""").forEach {
            assertNull(it, MetadataParser.parse(it))
        }
    }

    @Test fun R78_tolerantFieldShapes() {
        val json = """{"metadata":{"identifier":"t","mediatype":"audio","title":["Title A","Title B"],
            "language":["French","eng"],"subject":"jazz; swing","collection":"c1"},
            "files":[{"name":"a.mp3","source":"original","format":"VBR MP3","length":"bogus"}]}"""
        val item = MetadataParser.parse(json)!!
        assertEquals("Title A", item.title)
        assertEquals(setOf("fr", "en"), item.languages)
        assertEquals(listOf("jazz", "swing"), item.subjects)
        assertEquals(listOf("c1"), item.collections)
        assertNull(item.entries.single().durationSeconds)
    }

    @Test fun R12_missingTitleFallsBackToIdentifier() {
        val json = """{"metadata":{"identifier":"no_title","mediatype":"audio"},"files":[{"name":"a.mp3","source":"original","format":"VBR MP3"}]}"""
        assertEquals("no_title", MetadataParser.parse(json)!!.title)
    }

    @Test fun R11_naturalFilenameOrderWithoutTrackField() {
        val json = """{"metadata":{"identifier":"n","mediatype":"audio","title":"N"},"files":[
            {"name":"ep10.mp3","source":"original","format":"VBR MP3"},
            {"name":"ep2.mp3","source":"original","format":"VBR MP3"},
            {"name":"ep1.mp3","source":"original","format":"VBR MP3"}]}"""
        assertEquals(listOf("ep1", "ep2", "ep10"), MetadataParser.parse(json)!!.entries.map { it.title })
    }
}

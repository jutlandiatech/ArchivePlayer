package com.jutlandiatech.archiveplayer.core.catalog

import com.jutlandiatech.archiveplayer.core.support.Fixtures
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class CatalogUtilitiesTest {
    @Test fun R07_mediaKinds() {
        assertEquals(MediaKind.VIDEO, MediaKind.fromMediatype("movies"))
        assertEquals(MediaKind.AUDIO, MediaKind.fromMediatype("audio"))
        assertEquals(MediaKind.AUDIO, MediaKind.fromMediatype("etree"))
        assertNull(MediaKind.fromMediatype("texts"))
        assertNull(MediaKind.fromMediatype(null))
    }

    @Test fun R23_durationClasses() {
        assertEquals(DurationClass.SHORT, DurationClass.of(19 * 60.0))
        assertEquals(DurationClass.EPISODE, DurationClass.of(20 * 60.0))
        assertEquals(DurationClass.EPISODE, DurationClass.of(60 * 60.0))
        assertEquals(DurationClass.FEATURE, DurationClass.of(61 * 60.0))
    }

    @Test fun R12_durationFormats() {
        assertEquals(664.03, DurationParser.parseSeconds("664.03")!!, 0.001)
        assertEquals(663.0, DurationParser.parseSeconds("11:03")!!, 0.001)
        assertEquals(3723.0, DurationParser.parseSeconds("1:02:03")!!, 0.001)
        assertNull(DurationParser.parseSeconds("abc"))
        assertNull(DurationParser.parseSeconds(null))
    }

    @Test fun R45_subtitleClassification() {
        val srt = SubtitleDetector.classify("film.srt", "SubRip")!!
        assertEquals(SubtitleType.SRT, srt.type)
        assertFalse(srt.autoGenerated)
        assertNull(srt.language)
        assertTrue(SubtitleDetector.classify("film.asr.srt", "SubRip")!!.autoGenerated)
        val vtt = SubtitleDetector.classify("show.autogenerated.vtt", "Web Video Text Tracks")!!
        assertEquals(SubtitleType.VTT, vtt.type)
        assertTrue(vtt.autoGenerated)
        assertEquals("de", SubtitleDetector.classify("film.de.srt", null)!!.language)
        assertEquals("fr", SubtitleDetector.classify("film.French.vtt", null)!!.language)
        assertNull(SubtitleDetector.classify("film.mp4", "h.264"))
        assertNull(SubtitleDetector.classify("show.autogenerated.txt", "Text"))
    }

    @Test fun R12_R78_descriptionSanitized() {
        assertEquals("Hello world", HtmlSanitizer.toPlainText("<p>Hello <b>world</b></p><script>alert(1)</script>").trim())
        assertEquals("Tom & Jerry", HtmlSanitizer.toPlainText("Tom &amp; Jerry"))
        assertEquals("a\nb", HtmlSanitizer.toPlainText("a<br>b"))
        assertFalse(HtmlSanitizer.toPlainText("<a href=\"javascript:x\" onclick=\"y\">link</a>").contains("javascript"))
    }

    @Test fun A10_searchResponseParsed() {
        val page = SearchResponseParser.parse(Fixtures.archive("search_gunsmoke_audio.json"))
        assertEquals(435, page.total)
        assertEquals(5, page.hits.size)
        val first = page.hits[0]
        assertEquals("OTRR_Gunsmoke_Singles", first.identifier)
        assertEquals(MediaKind.AUDIO, first.kind)
        assertEquals(7392449L, first.downloads)
        assertEquals(page.hits.sortedByDescending { it.downloads }, page.hits)
    }

    @Test fun R78_searchGarbageGivesEmptyPage() {
        listOf("", "nope", "{}", """{"response":{"docs":"x"}}""").forEach {
            val page = SearchResponseParser.parse(it)
            assertEquals(0, page.total)
            assertTrue(page.hits.isEmpty())
        }
    }
}

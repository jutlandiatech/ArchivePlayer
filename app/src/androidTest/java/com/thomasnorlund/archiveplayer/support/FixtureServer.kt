package com.thomasnorlund.archiveplayer.support

import android.net.Uri
import androidx.test.platform.app.InstrumentationRegistry
import com.thomasnorlund.archiveplayer.AppEnvironment
import com.thomasnorlund.archiveplayer.NetworkKind
import okhttp3.mockwebserver.Dispatcher
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import okhttp3.mockwebserver.RecordedRequest
import okio.Buffer
import org.json.JSONArray
import org.json.JSONObject
import org.junit.rules.ExternalResource
import java.util.concurrent.CopyOnWriteArrayList
import java.util.concurrent.TimeUnit

/**
 * Local stand-in for archive.org and the GitHub Pages site, serving `androidTest/assets/fixtures`
 * (generated by tools/gen_ui_fixtures.py). Apply with `@get:Rule(order = 0)` so it is running and
 * [AppEnvironment] points at it before the activity starts.
 *
 * Routes: `/advancedsearch.php`, `/metadata/<id>`, `/download/<id>/<file>`, `/services/img/<id>`,
 * `/pages/...` (always 404 → bundled category map).
 */
class FixtureServer(
    private val network: NetworkKind = NetworkKind.WIFI,
    private val freeBytes: Long? = null,
) : ExternalResource() {
    private class Rule(val match: (RecordedRequest) -> Boolean, val respond: (RecordedRequest) -> MockResponse?, var remaining: Int)

    private val server = MockWebServer()
    private val rules = CopyOnWriteArrayList<Rule>()
    val requests = CopyOnWriteArrayList<RecordedRequest>()
    private val assets get() = InstrumentationRegistry.getInstrumentation().context.assets

    val baseUrl: String get() = server.url("/").toString().trimEnd('/')

    override fun before() {
        server.dispatcher = object : Dispatcher() {
            override fun dispatch(request: RecordedRequest): MockResponse {
                android.util.Log.i("Fixture", "${request.method} ${request.path}")
                requests += request
                rules.firstOrNull { it.remaining > 0 && it.match(request) }?.let { rule ->
                    rule.remaining--
                    rule.respond(request)?.let { return it }
                }
                return route(request)
            }
        }
        server.start()
        AppEnvironment.archiveBaseUrl = baseUrl
        AppEnvironment.pagesBaseUrl = "$baseUrl/pages"
        AppEnvironment.networkOverride = network
        AppEnvironment.freeBytesOverride = freeBytes
        AppEnvironment.shuffleSeed = 42L
    }

    override fun after() {
        AppEnvironment.reset()
        // A still-delayed response (H09) makes shutdown time out; the next test gets a fresh server anyway.
        runCatching { server.shutdown() }
    }

    /** Responds with [code] to the next [times] requests whose path matches [pathRegex]. */
    fun fail(pathRegex: String, code: Int = 503, times: Int = Int.MAX_VALUE) {
        rules.add(0, Rule({ Regex(pathRegex).containsMatchIn(it.path.orEmpty()) }, { MockResponse().setResponseCode(code) }, times))
    }

    /** Delays the body of matching responses by [millis]. */
    fun delay(pathRegex: String, millis: Long, times: Int = Int.MAX_VALUE) {
        rules.add(0, Rule({ Regex(pathRegex).containsMatchIn(it.path.orEmpty()) },
            { route(it).setBodyDelay(millis, TimeUnit.MILLISECONDS) }, times))
    }

    /** Serves the search fixture [fixture] (file name in fixtures/search without `.json`) for queries containing [term]. */
    fun searchFor(term: String, fixture: String) {
        rules.add(0, Rule({ it.isSearch() && it.query().contains(term, ignoreCase = true) }, { search(it, fixture) }, Int.MAX_VALUE))
    }

    /** Responds with [code] to the next [times] searches whose `q` contains [term]. */
    fun failSearch(term: String, code: Int = 503, times: Int = Int.MAX_VALUE) {
        rules.add(0, Rule({ it.isSearch() && it.query().contains(term, ignoreCase = true) }, { MockResponse().setResponseCode(code) }, times))
    }

    /** Delays searches whose `q` contains [term] by [millis]. */
    fun delaySearch(term: String, millis: Long, times: Int = Int.MAX_VALUE) {
        rules.add(0, Rule({ it.isSearch() && it.query().contains(term, ignoreCase = true) },
            { route(it).setBodyDelay(millis, TimeUnit.MILLISECONDS) }, times))
    }

    fun searchRequestsFor(term: String): List<RecordedRequest> = searchRequests().filter { it.query().contains(term, ignoreCase = true) }

    fun clearRules() = rules.clear()

    fun searchRequests(): List<RecordedRequest> = requests.filter { it.isSearch() }

    private fun RecordedRequest.isSearch() = path.orEmpty().startsWith("/advancedsearch.php")
    private fun RecordedRequest.query(): String = requestUrl?.queryParameter("q").orEmpty()

    private fun route(request: RecordedRequest): MockResponse {
        val path = Uri.parse(request.path.orEmpty()).path.orEmpty()
        return when {
            request.isSearch() -> search(request, builtInSearchFixture(request.query()))
            path.startsWith("/metadata/") -> json("fixtures/metadata/${path.removePrefix("/metadata/").substringBefore('/')}.json")
            path.startsWith("/download/") -> media(request, path.substringAfterLast('/'))
            path.startsWith("/services/img/") -> bytes("fixtures/media/art.png", "image/png", request)
            else -> MockResponse().setResponseCode(404)
        }
    }

    private fun builtInSearchFixture(q: String) = when {
        q.contains("gunsmoke", true) -> "gunsmoke"
        q.contains("nohits", true) -> "empty"
        q.contains("paging", true) -> "paging"
        else -> "default"
    }

    /** Serves a search fixture, honouring the mediatype clause and `rows`/`page` paging. */
    private fun search(request: RecordedRequest, fixture: String): MockResponse {
        val root = JSONObject(text("fixtures/search/$fixture.json"))
        val docs = root.getJSONObject("response").getJSONArray("docs")
        val q = request.query()
        // A query naming a recorded metadata fixture also finds that item (e.g. OTRR_Philip_Marlowe_Singles).
        Regex("^\\(([^()\\s]+)\\)").find(q)?.groupValues?.get(1)?.let { term ->
            val known = (0 until docs.length()).any { docs.getJSONObject(it).optString("identifier") == term }
            val meta = if (known) null else runCatching { JSONObject(text("fixtures/metadata/$term.json")).getJSONObject("metadata") }.getOrNull()
            if (meta != null) {
                val doc = JSONObject().put("identifier", term).put("title", meta.optString("title", term))
                    .put("mediatype", meta.optString("mediatype", "audio"))
                listOf("creator", "language", "collection", "date", "subject").forEach { k -> meta.opt(k)?.let { doc.put(k, it) } }
                docs.put(doc)
            }
        }
        val kinds = when {
            q.contains("mediatype:(movies)") -> setOf("movies")
            q.contains("mediatype:(audio OR etree)") -> setOf("audio", "etree")
            else -> null
        }
        val filtered = (0 until docs.length()).map { docs.getJSONObject(it) }
            .filter { kinds == null || it.optString("mediatype") in kinds || it.optString("mediatype") == "collection" }
        val rows = request.requestUrl?.queryParameter("rows")?.toIntOrNull() ?: 50
        val page = request.requestUrl?.queryParameter("page")?.toIntOrNull() ?: 1
        val slice = filtered.drop((page - 1) * rows).take(rows)
        val response = JSONObject().put("numFound", filtered.size).put("start", (page - 1) * rows).put("docs", JSONArray(slice))
        return MockResponse().setHeader("Content-Type", "application/json")
            .setBody(JSONObject().put("responseHeader", JSONObject().put("status", 0)).put("response", response).toString())
    }

    private fun media(request: RecordedRequest, file: String): MockResponse = when (file.substringAfterLast('.').lowercase()) {
        "mp3", "flac" -> bytes("fixtures/media/tone.mp3", "audio/mpeg", request)
        "ogg" -> bytes("fixtures/media/tone.ogg", "audio/ogg", request)
        "mp4" -> bytes("fixtures/media/clip.mp4", "video/mp4", request)
        "srt" -> bytes("fixtures/media/subs.srt", "application/x-subrip", request)
        "vtt" -> bytes("fixtures/media/subs.vtt", "text/vtt", request)
        "png", "jpg", "gif" -> bytes("fixtures/media/art.png", "image/png", request)
        else -> MockResponse().setResponseCode(404)
    }

    private fun text(asset: String) = assets.open(asset).bufferedReader().use { it.readText() }

    private fun json(asset: String): MockResponse = runCatching { text(asset) }
        .map { MockResponse().setHeader("Content-Type", "application/json").setBody(it) }
        .getOrElse { MockResponse().setResponseCode(200).setBody("{}") }

    /** Byte response with HTTP range support so the player can seek. */
    private fun bytes(asset: String, type: String, request: RecordedRequest): MockResponse {
        val all = assets.open(asset).use { it.readBytes() }
        val range = request.getHeader("Range")?.let { Regex("bytes=(\\d+)-(\\d*)").find(it) }
        if (range == null) return MockResponse().setHeader("Content-Type", type).setHeader("Accept-Ranges", "bytes").setBody(Buffer().write(all))
        val start = range.groupValues[1].toInt().coerceAtMost(all.size)
        val end = range.groupValues[2].toIntOrNull()?.coerceAtMost(all.size - 1) ?: (all.size - 1)
        return MockResponse().setResponseCode(206).setHeader("Content-Type", type).setHeader("Accept-Ranges", "bytes")
            .setHeader("Content-Range", "bytes $start-$end/${all.size}").setBody(Buffer().write(all.copyOfRange(start, end + 1)))
    }
}
